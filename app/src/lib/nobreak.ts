/**
 * Название с неразрывными дефисами: «Масджид аль-Акса» при нехватке места переносится только между словами
 * («Масджид» / «аль-Акса»), а частица «аль-» (ал-, ар-, ас-…) остаётся при своём слове, как и в арабском письме.
 * Искать и сравнивать надо по обычной строке — это только для показа.
 */
export const keepHyphen = (s: string) => s.replace(/-/g, '‑')
