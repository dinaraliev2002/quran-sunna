/** Названия «имя / сказуемое при частицах إنّ, كان и их сёстрах»: «اسم إن», «خبر كان» */
const PAIR = /^(اسم|خبر) (.+)$/

/** Русское название роли и пояснение; для главного слова предложения зависит от того, глагол это или имя */
export function roleInfo(ar: string, isVerb = false): Role {
  if (ar === 'root') {
    return isVerb
      ? { ru: 'Главный глагол предложения', hint: 'Глагол, на котором держится всё предложение.' }
      : { ru: 'Подлежащее именного предложения (мубтада)', hint: 'То, о чём говорится в предложении; к нему относится сказуемое (хабар).' }
  }
  const direct = ROLES[ar]
  if (direct) return direct
  const m = PAIR.exec(ar)
  if (m) {
    const subj = m[1] === 'اسم'
    return {
      ru: `${subj ? 'Подлежащее' : 'Сказуемое'} при «${m[2]}»`,
      hint: subj ? `Имя, которое стоит после «${m[2]}» и о котором идёт речь.` : `То, что сообщается о подлежащем после «${m[2]}».`,
    }
  }
  return { ru: ar, hint: '' }
}
