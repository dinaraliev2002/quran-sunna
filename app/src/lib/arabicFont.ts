// Подгонка арабского текста под выбранный шрифт.
// Шрифт Хафс (кодировка KFGQPC) рисует обычный сукун U+0652 круглым нулём, а знак U+06DF — пунктирным
// кружком; запятые «،» и «؛» — кружком с точкой. Для него меняем их на то, что он рисует правильно.

/** Текст для шрифта: для Хафса — сукун U+06E1, без U+06DF, обычные запятые; для остальных — как есть */
export function arForFont(text: string, font: string): string {
  if (font !== 'hafs') return text
  return text
    .replace(/\s+([ۖ-ۜ])/g, '$1') // знаки остановки — к предыдущему слову
    .replace(/ْ/g, 'ۡ')
    .replace(/۟/g, 'ْ')
    .replace(/[؛،]/g, ',')
}
