/** Понятие Корана: человек, место, существо, растение, предмет (онтология Quranic Arabic Corpus) */
export interface Concept {
  i: string // номер в корпусе (concept.jsp?id=…)
  ar: string // арабское написание
  ru: string // русское название
  en: string // английское название
  c: string[] // путь категорий: от общей к частной
  d: string // краткое пояснение по-русски (может быть пустым)
  v: string[] // аяты «сура:аят», где упоминается
  n: number // сколько всего слов-упоминаний
}

/** Тема Корана (смысл): раздел или подтема тематического указателя с аятами */
export interface Topic {
  i: number // номер в указателе
  p: number // номер родительской темы (0 — верхний уровень)
  ru: string // название по-русски
  a: string[] // аяты «сура:аят», где говорится об этой теме (без подтем)
}
