def cap(t, up=True):
    i = t.index('|') + 1 if t.startswith('{{') else 0
    return t[:i] + (t[i].upper() if up else t[i].lower()) + t[i + 1:]

def _grade_phrase(s):
    ws = s.split()
    if not ws or ws[0] not in ('ثقة', 'صدوق', 'ضعيف', 'مقبول', 'ثبت', 'حافظ', 'صالح', 'لين'): return None
    out = []
    for w in ws:
        if w not in W: return None
        out.append(W[w])
    r = ', '.join(out).replace(', в хадисах', ' в хадисах')
    return cap(r)

def _clause(c):
    c = c.strip()
    if c in EXACT and EXACT[c]: return EXACT[c]
    return _grade_phrase(c)

def translate(q):
    s = norm(q)
    if not s: return None
    if s in EXACT and EXACT[s]: return EXACT[s] + '.'
    # «Y ومرة Z»
    if ' ومرة ' in s:
        parts = [_clause(p) for p in s.split(' ومرة ')]
        if all(parts): return parts[0] + '. В другой раз сказал: ' + '; '.join('«' + cap(p) + '»' for p in parts[1:]) + '.'
        return None
    m = re.match(r'^قال في التقريب (.+)$', s)
    if m:
        c = _clause(m.group(1))
        return f'В «Такрибе» Ибн Хаджар пишет: «{cap(c)}».' if c else None
    m = re.match(r'^ذكره في (.+?)(?: وقال (.+))?$', s)
    if m and m.group(1) in BOOKS:
        b = BOOKS[m.group(1)]
        t = f'Упомянул его в {b}'
        if m.group(2):
            c = _clause(m.group(2))
            if not c: return None
            t += f' и сказал: «{cap(c)}»'
        return t + '.'
    c = _clause(s)
    return c + '.' if c else None
