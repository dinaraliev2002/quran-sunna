"""
Дополнения к «Крепости мусульманина» по самой книге — то, чего нет в базе muslim-data-android.

  • Утренние и вечерние азкары: первым идёт вступительное дуа автора
    «الحمد لله وحده، والصلاة والسلام على من لا نبي بعده» — с хадисом Анаса о достоинстве поминания в это время.
  • Аят аль-Курси утром и вечером: в базе к нему по ошибке приложен перевод из главы «после молитвы»
    («после каждой молитвы желательно…») и аудио оттуда же. Ставим перевод и запись для утра и вечера (хадис Убайя ибн Ка'ба, аль-Хаким 1/562).

Запуск после build-azkar.py и azkar-quran.py:  python scripts/azkar-additions.py   (повторный запуск ничего не портит)
"""
import json
import os
import sys

sys.stdout.reconfigure(encoding='utf-8')
PATH = os.path.join(os.path.dirname(__file__), '..', 'public', 'data', 'azkar.json')

OPENING_ID = '288'
OPENING = {
    'ch': 27,
    'ar': 'الْحَمْدُ لِلَّهِ وَحْدَهُ، وَالصَّلَاةُ وَالسَّلَامُ عَلَى مَنْ لَا نَبِيَّ بَعْدَهُ',
    'ru': 'Хвала одному лишь Аллаху, благословение и мир тому, после кого нет пророка.\n\n'
          'Этими словами автор «Крепости мусульманина» открывает главу утренних и вечерних поминаний. '
          'О достоинстве поминания в это время Анас передал, что Пророк (с.а.в.с.) сказал: '
          '«Сидеть с людьми, которые поминают Всевышнего Аллаха от утренней молитвы до восхода солнца, мне милее, '
          'чем освободить четырёх рабов из потомков Исмаила. И сидеть с людьми, которые поминают Аллаха '
          'от послеполуденной молитвы до заката солнца, мне милее, чем освободить четырёх рабов».',
    'ref': 'Abu Dawud 3667; al-Albani — hasan.',
    'rep': 1,
}
MORNING_CH, EVENING_CH = 27, 28

KURSI_RU = ('Я прибегаю к Аллаху от проклятого шайтана. «Аллах — нет бога, кроме Него, Живого, Вседержителя. '
            'Не овладевает Им ни дремота, ни сон, и Ему принадлежит то, что в небесах, и то, что на земле. '
            'Кто заступится пред Ним, иначе как с Его позволения? Ему известно, что [ждёт] их в будущем и что [было] '
            'с ними прежде, а они постигают из Его знания лишь то, что Он пожелает. Подножие Его трона объемлет небеса '
            'и землю, и не тяготит Его оберегание их. Поистине, Он — Высокий, Великий» (2:255).\n\n'
            'Кто прочтёт этот аят утром, будет защищён от джиннов до вечера, а кто прочтёт его вечером — '
            'будет защищён от них до утра.')
KURSI_ITEMS = ('75', '98')  # аят аль-Курси в главах «утром и вечером» и «вечером»
# запись из главы утренних азкаров hisnmuslim.com (№ 75) — с «أعوذ بالله…»; в базе стояла запись «после молитвы» (№ 71)
KURSI_AUDIO = 'https://www.hisnmuslim.com/audio/ar/75.mp3'


def main():
    az = json.load(open(PATH, encoding='utf8'))
    az['items'][OPENING_ID] = OPENING
    for ch in az['chapters']:
        if ch['id'] in (MORNING_CH, EVENING_CH) and ch['items'][:1] != [int(OPENING_ID)]:
            ch['items'] = [int(OPENING_ID)] + [i for i in ch['items'] if i != int(OPENING_ID)]
    for k in KURSI_ITEMS:
        az['items'][k]['ru'] = KURSI_RU
        az['items'][k]['audio'] = KURSI_AUDIO
    json.dump(az, open(PATH, 'w', encoding='utf8'), ensure_ascii=False, separators=(',', ':'))
    print('готово')


if __name__ == '__main__':
    main()
